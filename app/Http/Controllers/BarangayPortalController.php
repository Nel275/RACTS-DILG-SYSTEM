<?php

namespace App\Http\Controllers;

use App\Models\AuditLog;
use App\Models\BarangayLog;
use App\Models\BarangayLogDetail;
use App\Models\Notification;
use App\Models\ReportRecord;
use App\Models\ReportRequirement;
use App\Models\User;
use App\Services\RankingCalculator;
use App\Services\ReportEntryGenerator;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use Illuminate\View\View;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Panelist revision: the barangay-only side of RACTS. Everything here is
 * scoped to the signed-in user's own barangay (users.barangay_id) - the
 * barangay is never taken from the request, so a barangay user cannot
 * look at or change another barangay's data by editing a URL or form.
 */
class BarangayPortalController extends Controller
{
    public function __construct(
        private readonly RankingCalculator $ranking,
        private readonly ReportEntryGenerator $generator,
    ) {
    }

    /**
     * The personalized barangay dashboard (DashboardController hands
     * barangay accounts to this).
     */
    public function dashboard(Request $request): View
    {
        $user = $request->user();
        $barangay = $user->barangay;

        $this->generator->generate($barangay);
        $this->markOverdueAsMissed($barangay->id);

        $entries = BarangayLogDetail::with('barangayLog')->where('barangay_id', $barangay->id);

        // Compliance counts cover mandatory requirements only.
        $mandatory = (clone $entries)->whereHas('barangayLog', fn ($q) => $q->where('is_mandatory', true));
        $counts = [
            'pending' => (clone $mandatory)->where('status', BarangayLogDetail::STATUS_PENDING)->count(),
            'submitted' => (clone $mandatory)->whereIn('status', [BarangayLogDetail::STATUS_SUBMITTED, BarangayLogDetail::STATUS_CLOSED, BarangayLogDetail::STATUS_ACCEPTED])->count(),
            'late' => (clone $mandatory)->where('status', BarangayLogDetail::STATUS_LATE)->count(),
            'missed' => (clone $mandatory)->where('status', BarangayLogDetail::STATUS_MISSED)->count(),
            'returned' => (clone $mandatory)->where('status', BarangayLogDetail::STATUS_RETURNED)->count(),
        ];
        $counts['total'] = array_sum($counts);
        $counts['accepted'] = (clone $mandatory)->where('status', BarangayLogDetail::STATUS_ACCEPTED)->count();

        // Anything the barangay still has to file, most urgent first.
        $toSubmit = (clone $entries)
            ->whereIn('status', BarangayLogDetail::OPEN_STATUSES)
            ->orderBy('deadline_date')
            ->take(6)
            ->get();

        $recentSubmissions = (clone $entries)
            ->whereIn('status', BarangayLogDetail::SUBMITTED_STATUSES)
            ->orderByDesc('date_submitted')
            ->take(5)
            ->get();

        // Year-to-date standing in each council, from the same engine the
        // DILG Analytics page uses - so the numbers always agree.
        $yearStart = now()->startOfYear()->format('Y-m');
        $currentMonth = now()->format('Y-m');
        $standings = [];
        foreach ([ReportRequirement::COUNCIL_BARANGAY, ReportRequirement::COUNCIL_SK] as $council) {
            $rows = $this->ranking->rank($council, $yearStart, $currentMonth);
            $mine = $rows->first(fn ($row) => $row['barangay']->id === $barangay->id);
            $standings[$council] = [
                'label' => ReportRequirement::COUNCIL_TYPES[$council],
                'row' => $mine,
                'of' => $rows->count(),
            ];
        }

        $alerts = $user->notifications()->unread()->autoGenerated()->take(4)->get();

        // Only this barangay's own accounts' activity - never the DILG-wide feed.
        $accountIds = User::where('barangay_id', $barangay->id)->pluck('id');
        $recentActivity = AuditLog::with('user')
            ->whereIn('user_id', $accountIds)
            ->orderByDesc('log_date')->orderByDesc('id')
            ->take(5)
            ->get();

        // Grade mix from the compliance grid, for this barangay only.
        $grades = ReportRecord::where('barangay_id', $barangay->id)
            ->whereNotNull('status_color')
            ->selectRaw('status_color, COUNT(*) as total')
            ->groupBy('status_color')
            ->pluck('total', 'status_color');

        return view('portal.dashboard', compact(
            'user', 'barangay', 'counts', 'toSubmit', 'recentSubmissions',
            'standings', 'alerts', 'recentActivity', 'grades'
        ));
    }

    /**
     * My Reports: this barangay's own log entries, with filters and the
     * submit form.
     */
    public function reports(Request $request): View
    {
        $barangay = $request->user()->barangay;
        $this->generator->generate($barangay);
        $this->markOverdueAsMissed($barangay->id);

        $council = $request->query('council') === ReportRequirement::COUNCIL_SK
            ? ReportRequirement::COUNCIL_SK
            : ReportRequirement::COUNCIL_BARANGAY;
        $status = $request->string('status')->trim()->value();
        $search = $request->string('search')->trim()->value();
        $frequency = array_key_exists((string) $request->query('frequency'), BarangayLog::FREQUENCIES) ? $request->query('frequency') : '';
        $year = preg_match('/^\d{4}$/', (string) $request->query('year')) ? $request->query('year') : '';
        $month = preg_match('/^(0[1-9]|1[0-2])$/', (string) $request->query('month')) ? $request->query('month') : '';

        $entries = BarangayLogDetail::with(['barangayLog', 'stamps'])
            ->where('barangay_id', $barangay->id)
            ->whereHas('barangayLog', fn ($q) => $q->where('council_type', $council)
                ->when($frequency, fn ($q) => $q->where('frequency', $frequency)))
            ->when(array_key_exists($status, BarangayLogDetail::STATUSES), fn ($q) => $q->where('status', $status))
            // "Resubmitted" is a view over submitted/late entries filed more than once.
            ->when($status === 'resubmitted', fn ($q) => $q->where('submission_count', '>', 1)
                ->whereIn('status', [BarangayLogDetail::STATUS_SUBMITTED, BarangayLogDetail::STATUS_LATE]))
            ->when($year, fn ($q) => $q->where(fn ($q) => $q->where('period', 'like', $year.'%')
                ->orWhere(fn ($q) => $q->whereNull('period')->whereYear('deadline_date', $year))))
            ->when($month, fn ($q) => $q->where('period', 'like', '%-'.$month))
            ->when($search !== '', fn ($q) => $q->where('item_description', 'like', '%'.$search.'%'))
            ->orderByRaw("CASE status WHEN 'returned' THEN 0 WHEN 'missed' THEN 1 WHEN 'pending' THEN 2 WHEN 'late' THEN 3 WHEN 'submitted' THEN 4 ELSE 5 END")
            ->orderBy('deadline_date')
            ->paginate(10)
            ->withQueryString();

        return view('portal.reports', compact('entries', 'barangay', 'council', 'status', 'search', 'frequency', 'year', 'month'));
    }

    /**
     * The barangay files its own report: the date submitted is always
     * "now" (server time), so lateness is decided by the system, not
     * typed in. Only entries still open (pending/missed) can be filed.
     */
    public function submit(Request $request, BarangayLogDetail $barangayLogDetail): RedirectResponse
    {
        $this->authorizeEntry($request, $barangayLogDetail);

        if (! $barangayLogDetail->isOpenForSubmission()) {
            return back()->with('error', 'This report has already been submitted.');
        }

        $request->validate([
            'report_file' => ['required', 'file', 'mimes:pdf,doc,docx,jpg,jpeg,png', 'max:10240'],
        ], [
            'report_file.required' => 'Please attach the report file.',
            'report_file.mimes' => 'The report must be a PDF, Word document, or JPG/PNG image.',
            'report_file.max' => 'The report file must be 10 MB or smaller.',
        ]);

        $user = $request->user();
        $file = $request->file('report_file');

        $path = $file->store($barangayLogDetail->incomingFolder(), 'local');

        $barangayLogDetail->markSubmitted(now(), $user->name, $path, $file->getClientOriginalName());
        $barangayLogDetail->refresh()->fileIntoBarangayFolder($user->name);

        Notification::notifyBarangay($barangayLogDetail->barangay_id, Notification::TYPE_REPORT_RECEIVED, sprintf(
            'DILG received your report "%s"%s (%s).',
            $barangayLogDetail->item_description,
            $barangayLogDetail->period ? ' for '.$barangayLogDetail->periodLabel() : '',
            $barangayLogDetail->statusLabel()
        ), $barangayLogDetail);

        AuditLog::record($user, sprintf(
            '%s report "%s" (%s) - %s.',
            $barangayLogDetail->isResubmission() ? 'Resubmitted' : 'Submitted',
            $barangayLogDetail->item_description,
            $barangayLogDetail->barangay->barangay_name,
            $barangayLogDetail->statusLabel()
        ));

        return back()->with('success', $barangayLogDetail->status === BarangayLogDetail::STATUS_LATE
            ? 'Report submitted. It was filed after the deadline, so it is marked late.'
            : 'Report submitted on time. Thank you!');
    }

    public function viewFile(Request $request, BarangayLogDetail $barangayLogDetail): StreamedResponse
    {
        $this->authorizeEntry($request, $barangayLogDetail);

        abort_unless($barangayLogDetail->hasReportFile(), 404);
        abort_unless(Storage::disk('local')->exists($barangayLogDetail->report_file_path), 404);

        $extension = strtolower(pathinfo($barangayLogDetail->report_original_name ?? '', PATHINFO_EXTENSION));
        $mime = match ($extension) {
            'pdf' => 'application/pdf',
            'jpg', 'jpeg' => 'image/jpeg',
            'png' => 'image/png',
            'doc' => 'application/msword',
            'docx' => 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
            default => 'application/octet-stream',
        };

        return Storage::disk('local')->response(
            $barangayLogDetail->report_file_path,
            $barangayLogDetail->report_original_name,
            ['Content-Type' => $mime]
        );
    }

    /**
     * The DILG-stamped copy of this barangay's own report - only the stamp
     * covering the file currently on record, never a superseded one.
     */
    public function stampedFile(Request $request, BarangayLogDetail $barangayLogDetail): StreamedResponse
    {
        $this->authorizeEntry($request, $barangayLogDetail);

        $stamp = $barangayLogDetail->currentStamp();
        abort_unless($stamp !== null, 404);

        return DigitalStampingController::streamStamp($stamp);
    }

    /**
     * Hard stop for cross-barangay access: an entry that isn't this
     * user's own barangay's behaves as if it doesn't exist.
     */
    private function authorizeEntry(Request $request, BarangayLogDetail $entry): void
    {
        abort_unless($entry->barangay_id === $request->user()->barangay_id, 404);
    }

    /**
     * Same self-healing sweep the DILG Report Filing list does, limited
     * to this barangay: pending entries past their deadline become missed.
     */
    private function markOverdueAsMissed(int $barangayId): void
    {
        BarangayLogDetail::where('barangay_id', $barangayId)
            ->where('status', BarangayLogDetail::STATUS_PENDING)
            ->whereDate('deadline_date', '<', now()->toDateString())
            ->update(['status' => BarangayLogDetail::STATUS_MISSED]);
    }
}
