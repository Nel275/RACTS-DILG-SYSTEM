<?php

namespace App\Http\Controllers;

use App\Models\Notification;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\View\View;

class NotificationController extends Controller
{
    /**
     * List the logged-in user's automated late-report alerts, newest
     * first (client spec Section 3.6: this page is repurposed to show
     * only system-generated entries - the old idea of a general/manual
     * notification doesn't exist in RACTS any more, since nothing has
     * ever created one by hand).
     *
     * Nothing populates this yet: the `racts:check-late-submissions`
     * scheduled command that actually generates these (client spec
     * Section 4) is Phase 6. Filtering to `auto_generated` now, ahead
     * of that command existing, means this page needs no further
     * changes once it does - it'll just stop being empty.
     */
    public function index(Request $request): View
    {
        $notifications = $request->user()
            ->notifications()
            ->autoGenerated()
            ->with('reportRecord.barangay', 'reportRecord.reportRequirement', 'barangay', 'reportRequirement')
            ->paginate(15);

        return view('notifications.index', compact('notifications'));
    }

    /**
     * Mark a single notification as read. Restricted to the notification's
     * own owner - one user should never be able to mark another user's
     * notification as read.
     */
    public function markRead(Request $request, Notification $notification): RedirectResponse
    {
        abort_if($notification->user_id !== $request->user()->id, 403);

        $notification->markAsRead();

        return back();
    }

    /**
     * Mark every unread notification belonging to the logged-in user as
     * read.
     */
    public function markAllRead(Request $request): RedirectResponse
    {
        $request->user()->notifications()->unread()->update(['is_read' => true]);

        return back()->with('success', 'All notifications marked as read.');
    }

    /**
     * Deletes every notification belonging to the logged-in user - read
     * and unread alike. Unlike the dashboard's "Clear History" (which
     * deliberately only clears a log derived from real report data),
     * notifications ARE the actual record here, so this really does
     * delete rows - but only ever this one user's own, never another
     * user's or the automation's ability to notify anyone else. Open to
     * both roles, since each person is only ever clearing their own
     * list.
     */
    public function clearAll(Request $request): RedirectResponse
    {
        $request->user()->notifications()->delete();

        return redirect()->route('notifications.index')->with('success', 'Notifications cleared.');
    }
}
